#!/usr/bin/env node
// /demo/*.html 디렉토리를 스캔해서 functions/demo/_known-assets.js 를 자동 생성.
//
// 사용법:
//   node scripts/sync-demo-assets.js          → 갱신
//   node scripts/sync-demo-assets.js --check  → 실제 파일과 일치하는지만 검사 (CI 용)
//
// 새 데모 파일 추가/삭제 후 갱신 안 하면 화이트리스트가 어긋나서:
// - 새 파일을 추가했는데 갱신 안 함 → 함수가 그 파일을 미지의 슬러그로 인식 →
//   _blank shell 로 fallback (실제 콘텐츠 안 뜸)
// - 파일을 삭제했는데 갱신 안 함 → 그 슬러그 요청이 next() 로 흘러 404 나
//   워크스페이스 랜딩 fallback 으로 이어짐
//
// CI 가 --check 모드로 매 PR 마다 실행해서 어긋남을 사전 차단.

'use strict';

const fs = require('fs');
const path = require('path');

const REPO_ROOT = path.resolve(__dirname, '..');
const DEMO_DIR = path.join(REPO_ROOT, 'demo');
const TARGET = path.join(REPO_ROOT, 'functions', 'demo', '_known-assets.js');

function listDemoHtml() {
  return fs.readdirSync(DEMO_DIR)
    .filter((name) => name.endsWith('.html'))
    .sort();
}

function generateContent(assets) {
  const items = assets.map((a) => `  '${a}',`).join('\n');
  return [
    '// AUTO-GENERATED by scripts/sync-demo-assets.js — do not edit manually.',
    '// 새 데모 파일 추가/삭제 시 `node scripts/sync-demo-assets.js` 실행하면 갱신.',
    '// CI 에서 이 파일이 demo/ 실제 상태와 다르면 빌드 실패 (check-demo-fn.yml).',
    '//',
    '// `_` 로 시작하는 파일은 Cloudflare Pages Functions 라우팅에서 제외돼',
    '// 일반 import 로만 쓰임.',
    'export const KNOWN_DEMO_ASSETS = [',
    items,
    '];',
    '',
  ].join('\n');
}

function main() {
  const checkMode = process.argv.includes('--check');
  const assets = listDemoHtml();
  const expected = generateContent(assets);

  if (checkMode) {
    let actual;
    try { actual = fs.readFileSync(TARGET, 'utf8'); } catch (_) { actual = ''; }
    if (actual !== expected) {
      console.error('[sync-demo-assets] ❌ functions/demo/_known-assets.js 가 demo/ 실제 상태와 다릅니다.');
      console.error('  → `node scripts/sync-demo-assets.js` 실행 후 커밋하세요.');
      console.error('');
      console.error('  expected demo/*.html 목록:');
      assets.forEach((a) => console.error('    - ' + a));
      process.exit(1);
    }
    console.log('[sync-demo-assets] ✅ functions/demo/_known-assets.js 가 demo/ 실제 상태와 일치 (' + assets.length + ' 파일).');
    return;
  }

  fs.writeFileSync(TARGET, expected, 'utf8');
  console.log('[sync-demo-assets] ✅ functions/demo/_known-assets.js 갱신 완료 (' + assets.length + ' 파일).');
  assets.forEach((a) => console.log('    - ' + a));
}

main();
